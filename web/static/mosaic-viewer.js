/* Mosaic viewer for docs/mosaics.md: OpenSeadragon on the Deep Zoom tiles, plus an optional read-only schema layer
   (data-schema: the boxed parts, pads, test points and vias, the traced top-layer copper and the beeps, generated by
   the bench navigator's export into images/mosaics/<set>.schema.json). Nothing here writes anywhere. */
(function () {
  "use strict";
  var SVGNS = "http://www.w3.org/2000/svg";
  var KIND = { part: "part", connector: "connector", pin: "pad", testpoint: "test point", via: "via" };
  var CONF_WORD = { confirmed: "confirmed", likely: "likely", guess: "guess" };
  var LAYERS = [
    ["parts", "Parts"], ["pads", "Pads & test points"], ["vias", "Vias"], ["traces", "Traces"], ["beeps", "Beeps"]
  ];
  var LINKS = {
    nets: "../hardware/nets-top/", j8: "../hardware/j8/", bom: "../hardware/components/",
    tp: "../hardware/testpoints/", nets2: "../hardware/nets/"
  };

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function svg(tag, attrs) {
    var e = document.createElementNS(SVGNS, tag);
    for (var k in attrs) e.setAttribute(k, attrs[k]);
    return e;
  }
  function layerOf(p) {
    return p.k === "part" || p.k === "connector" ? "parts" : p.k === "via" ? "vias" : "pads";
  }
  function natural(a, b) {
    return a.localeCompare(b, undefined, { numeric: true });
  }

  document.querySelectorAll(".mosaic-viewer").forEach(function (el0) {
    var viewer = OpenSeadragon({
      element: el0,
      tileSources: el0.dataset.dzi,
      prefixUrl: "https://cdnjs.cloudflare.com/ajax/libs/openseadragon/5.0.1/images/",
      showNavigator: true,
      maxZoomPixelRatio: 4,
      visibilityRatio: 0.5,
      gestureSettingsMouse: { clickToZoom: false },
      gestureSettingsTouch: { clickToZoom: false }
    });
    var vp = viewer.viewport, pointer = null, hoverText = "", schema = null;
    var bar = el("div", "mosaic-readout");
    var oneToOne = el("button", null, "1:1");
    oneToOne.title = "Zoom to 100 %";
    oneToOne.onclick = function () { vp.zoomTo(vp.imageToViewportZoom(1)); };
    var text = el("span");
    bar.append(oneToOne, text);
    viewer.addControl(bar, { anchor: OpenSeadragon.ControlAnchor.BOTTOM_LEFT });

    function show() {
      if (!viewer.world.getItemCount()) return;
      var s = Math.round(vp.viewportToImageZoom(vp.getZoom(true)) * 100) + " %";
      if (pointer) {
        var p = vp.viewerElementToImageCoordinates(pointer);
        s = "x " + Math.round(p.x) + "  y " + Math.round(p.y) + " px  ·  " + s;
        if (schema) s += "  ·  " + schema.mm(p) + (hoverText ? "  ·  " + hoverText : "");
      }
      text.textContent = s;
    }
    viewer.addHandler("open", show);
    viewer.addHandler("animation", show);
    new OpenSeadragon.MouseTracker({
      element: viewer.canvas,
      moveHandler: function (e) { pointer = e.position; if (schema) schema.hover(pointer); show(); },
      leaveHandler: function () { pointer = null; if (schema) schema.hover(null); show(); }
    });

    if (el0.dataset.schema) {
      fetch(el0.dataset.schema).then(function (r) {
        if (!r.ok) throw new Error(r.status + " " + r.statusText);
        return r.json();
      }).then(function (data) {
        schema = schemaLayer(viewer, el0, data, function (t) { hoverText = t; show(); });
      }).catch(function (err) {
        var note = el("p", "mosaic-schema-error", "The schema layer could not be loaded (" + err.message + ").");
        el0.parentNode.insertBefore(note, el0);
      });
    }
  });

  function schemaLayer(viewer, host, data, onHover) {
    var vp = viewer.viewport;
    var places = data.places, traces = data.traces, beeps = data.beeps || [];
    var byId = {}, netPlaces = {}, netTraces = {}, pinsOf = {}, beepsOf = {};
    places.forEach(function (p) {
      byId[p.id] = p;
      var b = p.b, r = (b[4] || 0) * Math.PI / 180;
      p.cx = b[0]; p.cy = b[1]; p.w = b[2]; p.h = b[3]; p.cos = Math.cos(r); p.sin = Math.sin(r);
      p.round = b[5] === 1; p.layer = layerOf(p);
      if (p.n != null) (netPlaces[p.n] = netPlaces[p.n] || []).push(p);
      if (p.of) (pinsOf[p.of] = pinsOf[p.of] || []).push(p);
    });
    traces.forEach(function (t, i) {
      t.i = i;
      if (t.n != null) (netTraces[t.n] = netTraces[t.n] || []).push(t);
      var x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
      t.p.forEach(function (q) { x0 = Math.min(x0, q[0]); y0 = Math.min(y0, q[1]); x1 = Math.max(x1, q[0]); y1 = Math.max(y1, q[1]); });
      t.bb = [x0, y0, x1, y1];
    });
    beeps.forEach(function (b) {
      (beepsOf[b.a] = beepsOf[b.a] || []).push(b);
      (beepsOf[b.b] = beepsOf[b.b] || []).push(b);
    });

    /* ---- toolbar above the viewer, panel over its right edge (both outside OpenSeadragon's own element) ---- */
    var wrap = el("div", "mosaic-wrap");
    host.parentNode.insertBefore(wrap, host);
    var tools = el("div", "mosaic-schema-bar");
    wrap.append(tools, host);
    var onLbl = el("label", "mosaic-schema-on");
    var onBox = el("input"); onBox.type = "checkbox";
    onLbl.append(onBox, document.createTextNode(" Schema"));
    tools.append(onLbl);
    var layerBoxes = {};
    var layerSpan = el("span", "mosaic-schema-layers");
    LAYERS.forEach(function (L) {
      var lb = el("label", "lyr-" + L[0]);
      var cb = el("input"); cb.type = "checkbox"; cb.checked = L[0] !== "vias";
      cb.onchange = applyLayers;
      layerBoxes[L[0]] = cb;
      lb.append(cb, el("i", "swatch"), document.createTextNode(L[1]));
      layerSpan.append(lb);
    });
    tools.append(layerSpan);
    var listId = "mosaic-schema-names-" + Math.random().toString(36).slice(2, 8);
    var search = el("input", "mosaic-schema-search");
    search.type = "search"; search.placeholder = "Find U7.29, TP33, J8…"; search.setAttribute("list", listId);
    search.setAttribute("aria-label", "Find a part, pad or test point");
    var dl = el("datalist"); dl.id = listId;
    places.filter(function (p) { return p.k !== "via"; }).map(function (p) { return p.id; }).sort(natural)
      .forEach(function (id) { var o = el("option"); o.value = id; dl.append(o); });
    search.addEventListener("change", function () { find(search.value); });
    search.addEventListener("keydown", function (e) { if (e.key === "Enter") find(search.value); });
    tools.append(search, dl);

    var panel = el("aside", "mosaic-schema-panel");
    panel.hidden = true;
    wrap.append(panel);

    /* ---- the SVG, one group transformed with the viewport ---- */
    var root = svg("svg", { class: "mosaic-schema" });
    var g = svg("g", {});
    root.append(g);
    viewer.canvas.append(root);
    var gTraces = svg("g", { class: "s-traces" }), gVias = svg("g", { class: "s-vias" }),
        gParts = svg("g", { class: "s-parts" }), gPads = svg("g", { class: "s-pads" }),
        gBeeps = svg("g", { class: "s-beeps" });
    g.append(gTraces, gParts, gVias, gPads, gBeeps);

    function shape(p) {
      var s;
      if (p.round) {
        s = svg("ellipse", { cx: p.cx, cy: p.cy, rx: Math.max(p.w, 20) / 2, ry: Math.max(p.h, 20) / 2 });
      } else {
        var w = Math.max(p.w, 20), h = Math.max(p.h, 20);
        s = svg("rect", { x: p.cx - w / 2, y: p.cy - h / 2, width: w, height: h });
      }
      if (p.b[4]) s.setAttribute("transform", "rotate(" + p.b[4] + " " + p.cx + " " + p.cy + ")");
      s.setAttribute("class", "k-" + p.k + (p.nf ? " nf" : ""));
      p.el = s;
      return s;
    }
    places.forEach(function (p) {
      (p.layer === "parts" ? gParts : p.layer === "vias" ? gVias : gPads).append(shape(p));
    });
    traces.forEach(function (t) {
      t.el = svg("polyline", { points: t.p.map(function (q) { return q[0] + "," + q[1]; }).join(" ") });
      gTraces.append(t.el);
    });
    beeps.forEach(function (b) {
      var a = byId[b.a], c = byId[b.b];
      if (!a || !c) return;
      b.el = svg("line", { x1: a.cx, y1: a.cy, x2: c.cx, y2: c.cy });
      gBeeps.append(b.el);
    });

    function place() {
      var o = vp.imageToViewerElementCoordinates(new OpenSeadragon.Point(0, 0));
      var u = vp.imageToViewerElementCoordinates(new OpenSeadragon.Point(1000, 0));
      var s = (u.x - o.x) / 1000;
      g.setAttribute("transform", "translate(" + o.x + " " + o.y + ") scale(" + s + ")");
      root.classList.toggle("far", s < 0.06);
    }
    viewer.addHandler("animation", place);
    viewer.addHandler("open", place);
    viewer.addHandler("resize", place);
    place();

    function on() { return onBox.checked; }
    function applyLayers() {
      root.style.display = on() ? "" : "none";
      layerSpan.classList.toggle("off", !on());
      LAYERS.forEach(function (L) { root.classList.toggle("hide-" + L[0], !layerBoxes[L[0]].checked); });
      if (!on()) { if (selected.length) select(null); setHover(null); }
    }
    onBox.onchange = function () { applyLayers(); };

    /* ---- hit test in image px: small places first, then traces, then parts ---- */
    function screenPx() { return 1 / Math.max(vp.viewportToImageZoom(vp.getZoom(true)), 1e-6); }
    function inside(p, x, y, tol) {
      var dx = x - p.cx, dy = y - p.cy;
      var lx = dx * p.cos + dy * p.sin, ly = -dx * p.sin + dy * p.cos;
      var w = Math.max(p.w, 20) / 2 + tol, h = Math.max(p.h, 20) / 2 + tol;
      if (p.round) return (lx * lx) / (w * w) + (ly * ly) / (h * h) <= 1;
      return Math.abs(lx) <= w && Math.abs(ly) <= h;
    }
    function segDist(x, y, a, b) {
      var vx = b[0] - a[0], vy = b[1] - a[1], l = vx * vx + vy * vy;
      var t = l ? Math.max(0, Math.min(1, ((x - a[0]) * vx + (y - a[1]) * vy) / l)) : 0;
      var px = a[0] + t * vx - x, py = a[1] + t * vy - y;
      return Math.sqrt(px * px + py * py);
    }
    function visible(layer) { return on() && layerBoxes[layer].checked && !(layer !== "parts" && layer !== "traces" && root.classList.contains("far")); }
    function hit(pt) {
      var x = pt.x, y = pt.y, px = screenPx(), tol = 3 * px, best = null, area = Infinity;
      ["pads", "vias"].forEach(function (layer) {
        if (!visible(layer)) return;
        places.forEach(function (p) {
          if (p.layer !== layer || !inside(p, x, y, tol)) return;
          var a = Math.max(p.w, 20) * Math.max(p.h, 20);
          if (a < area) { area = a; best = { place: p }; }
        });
      });
      if (best) return best;
      if (visible("traces")) {
        var lim = 5 * px, bt = null;
        traces.forEach(function (t) {
          if (x < t.bb[0] - lim || x > t.bb[2] + lim || y < t.bb[1] - lim || y > t.bb[3] + lim) return;
          for (var i = 1; i < t.p.length; i++) {
            var d = segDist(x, y, t.p[i - 1], t.p[i]);
            if (d < lim) { lim = d; bt = t; }
          }
        });
        if (bt) return { trace: bt };
      }
      if (visible("parts")) {
        places.forEach(function (p) {
          if (p.layer !== "parts" || !inside(p, x, y, tol)) return;
          var a = p.w * p.h;
          if (a < area) { area = a; best = { place: p }; }
        });
      }
      return best;
    }

    /* ---- hover ---- */
    var hovered = null, raf = 0, lastPt = null;
    function setHover(h) {
      var e = h && (h.place ? h.place.el : h.trace.el);
      if (hovered === e) return;
      if (hovered) hovered.classList.remove("hover");
      hovered = e || null;
      if (hovered) hovered.classList.add("hover");
      onHover(h ? (h.place ? label(h.place) : "trace, " + netName(h.trace.n)) : "");
      viewer.canvas.style.cursor = h ? "pointer" : "";
    }
    function hover(pos) {
      lastPt = pos;
      if (!on()) return;
      if (raf) return;
      raf = requestAnimationFrame(function () {
        raf = 0;
        setHover(lastPt ? hit(vp.viewerElementToImageCoordinates(lastPt)) : null);
      });
    }

    /* ---- selection: a place or a net ---- */
    var selected = [];
    function clearSel() {
      selected.forEach(function (e) { e.classList.remove("sel", "sel-main"); });
      selected = [];
      root.classList.remove("has-sel");
    }
    function mark(e, main) { if (e) { e.classList.add("sel"); if (main) e.classList.add("sel-main"); selected.push(e); } }
    function select(h, fly) {
      clearSel();
      if (!h) { panel.hidden = true; setHash(""); return; }
      root.classList.add("has-sel");
      var p = h.place, n = p ? p.n : h.trace.n;
      if (n != null) {
        (netTraces[n] || []).forEach(function (t) { mark(t.el); });
        (netPlaces[n] || []).forEach(function (q) { mark(q.el); });
      }
      if (p) {
        mark(p.el, true);
        (pinsOf[p.id] || []).forEach(function (q) { mark(q.el); });
        (beepsOf[p.id] || []).forEach(function (b) { mark(b.el); var o = byId[b.a === p.id ? b.b : b.a]; if (o) mark(o.el); });
        setHash(p.id);
      } else {
        mark(h.trace.el, true);
        setHash("");
      }
      fill(p, n, h.trace);
      if (p && fly) flyTo(p);
    }
    /* Fit the place into the part of the viewer the panel leaves free: beside it on a wide screen, above it on a
       narrow one (the panel then sits at the bottom). */
    function flyTo(p) {
      var r = Math.max(p.w, p.h, 600) * 1.6;
      var vw = host.clientWidth || 1, vh = host.clientHeight || 1;
      var bottom = panel.offsetTop > vh / 3;
      var fx = bottom ? 0 : Math.min(panel.offsetWidth / vw, 0.6);
      var fy = bottom ? Math.min(panel.offsetHeight / vh, 0.6) : 0;
      var w = 2 * r / (1 - fx), h = 2 * r / (1 - fy);
      vp.fitBounds(vp.imageToViewportRectangle(p.cx - r, p.cy - r, w, h));
    }
    function find(q) {
      q = (q || "").trim();
      if (!q) return;
      var p = byId[q] || byId[q.toUpperCase()];
      if (!p) {
        var lc = q.toLowerCase();
        p = places.find(function (x) { return x.k !== "via" && x.id.toLowerCase() === lc; }) ||
            places.find(function (x) { return x.k !== "via" && x.sig && x.sig.toLowerCase() === lc; });
      }
      if (!p) { search.setCustomValidity("Not on this side's schema"); search.reportValidity(); return; }
      search.setCustomValidity("");
      if (!on()) { onBox.checked = true; applyLayers(); }
      if (!layerBoxes[p.layer].checked) { layerBoxes[p.layer].checked = true; applyLayers(); }
      select({ place: p }, true);
    }
    function setHash(id) {
      var want = id ? "#schema:" + id : "";
      if (location.hash.indexOf("#schema") !== 0 && !id) return;
      try { history.replaceState(null, "", location.pathname + location.search + want); } catch (e) { /* file:// */ }
    }

    viewer.addHandler("canvas-click", function (e) {
      if (!e.quick || !on()) return;
      select(hit(vp.viewerElementToImageCoordinates(e.position)));
    });
    document.addEventListener("keydown", function (e) { if (e.key === "Escape" && !panel.hidden) select(null); });

    /* ---- the panel ---- */
    function label(p) {
      return p.id + (p.sig ? " " + p.sig.split(" (")[0] : "") + (p.nf ? " (not fitted)" : "");
    }
    function named(n) {
      return (netPlaces[n] || []).filter(function (q) { return q.k !== "via"; });
    }
    function netName(n) {
      if (n == null) return "no net";
      var m = named(n).map(function (q) { return q.id; }).sort(natural);
      return m.length ? m.slice(0, 3).join(", ") + (m.length > 3 ? " +" + (m.length - 3) : "") : "vias only";
    }
    function conf(word) {
      return el("span", "conf conf-" + word, CONF_WORD[word] || word);
    }
    function row(dl, k, v) {
      var dt = el("dt", null, k), dd = el("dd");
      if (typeof v === "string") dd.textContent = v; else dd.append.apply(dd, v);
      dl.append(dt, dd);
    }
    function chip(p) {
      var b = el("button", "chip" + (p.nf ? " nf" : ""), p.id + (p.sig ? " · " + p.sig.split(" (")[0] : ""));
      b.type = "button";
      b.onclick = function () { select({ place: p }, true); };
      return b;
    }
    function link(href, t) { var a = el("a", null, t); a.href = href; return a; }
    function mm(p) {
      return ((p.cx - data.fid1[0]) / data.pxPerMm).toFixed(1) + ", " + ((p.cy - data.fid1[1]) / data.pxPerMm).toFixed(1) + " mm";
    }

    function fill(p, n, t) {
      panel.textContent = "";
      var close = el("button", "close", "×");
      close.type = "button"; close.title = "Close (Esc)"; close.onclick = function () { select(null); };
      panel.append(close);
      var d = el("dl");
      if (p) {
        panel.append(el("h4", null, p.id), el("p", "kind", KIND[p.k] + (p.nf ? ", not fitted on this unit" : "")));
        if (p.of) {
          var parent = byId[p.of];
          row(d, "Pin", [document.createTextNode((p.pin || "?") + " of "), parent ? chip(parent) : document.createTextNode(p.of)]);
          if (p.sig && p.of === "J8") {
            row(d, "Function", p.sig);
            if (p.fc) row(d, "J8 row", [conf(p.fc), document.createTextNode(" "), link(LINKS.j8, "pin table")]);
          } else if (p.sig) {
            row(d, "Pin name", p.sig + (/^U\d/.test(p.of) ? " (datasheet)" : ""));
          }
        }
        if (p.part) row(d, "Part", [document.createTextNode(p.part + " "), p.pc ? conf(p.pc) : ""]);
        if (p.fn) row(d, "Does", p.fn);
        if (p.mark) row(d, "Marking", p.mark);
        if (p.pkg) row(d, "Package", p.pkg);
        if (p.nc) row(d, "Name", [document.createTextNode(p.k === "testpoint" ? "as boxed on the mosaic " : "from the silkscreen "), conf(p.nc)]);
        row(d, "Position", mm(p) + " from FID1");
        var bs = beepsOf[p.id] || [];
        if (bs.length) {
          var bl = [];
          bs.forEach(function (b) { var o = byId[b.a === p.id ? b.b : b.a]; if (o) bl.push(chip(o)); });
          bl.push(conf("confirmed"));
          row(d, "Beeped to", bl);
        }
        var pins = (pinsOf[p.id] || []).slice().sort(function (a, b) { return natural(a.pin || a.id, b.pin || b.id); });
        if (pins.length) {
          var box = el("div", "chips");
          pins.forEach(function (q) { box.append(chip(q)); });
          row(d, pins.length + " pads", [box]);
        }
      } else {
        panel.append(el("h4", null, "Trace"), el("p", "kind", (t.mm != null ? t.mm.toFixed(1) + " mm, " : "") + "top layer"));
      }
      panel.append(d);
      if (n != null) {
        var mem = named(n).filter(function (q) { return !p || q.id !== p.id; }).sort(function (a, b) { return natural(a.id, b.id); });
        var vias = (netPlaces[n] || []).filter(function (q) { return q.k === "via"; }).length;
        var tr = netTraces[n] || [], len = tr.reduce(function (s, x) { return s + (x.mm || 0); }, 0);
        var sec = el("section", "net");
        sec.append(el("h5", null, "Top-layer net"));
        var line = el("p");
        line.append(document.createTextNode(tr.length + " trace" + (tr.length === 1 ? "" : "s") + ", " + len.toFixed(1) +
          " mm" + (vias ? ", " + vias + " via" + (vias === 1 ? "" : "s") : "") + " "), conf("likely"));
        sec.append(line);
        if (mem.length) {
          var c = el("div", "chips");
          mem.forEach(function (q) { c.append(chip(q)); });
          sec.append(c);
        } else if (p) {
          sec.append(el("p", "muted", "Nothing else named on it on the top layer."));
        }
        sec.append(el("p", "muted", "Seen on the mosaic and approved as drawn, not measured. It stops at vias: the net may go on through another layer."));
        panel.append(sec);
      } else if (p && p.k !== "part" && p.k !== "connector") {
        panel.append(el("p", "muted", "No traced copper leaves it on the top layer."));
      }
      var more = el("p", "more");
      more.append(link(LINKS.nets, "All top-layer nets"));
      if (p && (p.id === "J8" || p.of === "J8")) more.append(document.createTextNode(" · "), link(LINKS.j8, "J8 pin table"));
      if (p && (p.k === "part" || p.k === "connector")) more.append(document.createTextNode(" · "), link(LINKS.bom, "Components"));
      if (p && p.k === "testpoint") more.append(document.createTextNode(" · "), link(LINKS.tp, "Test points"));
      panel.append(more);
      panel.hidden = false;
      panel.scrollTop = 0;
    }

    /* ---- a link to #schema:<name> opens the layer on it ---- */
    function fromHash() {
      var m = /^#schema(?::(.+))?$/.exec(decodeURIComponent(location.hash || ""));
      if (!m) return;
      onBox.checked = true; applyLayers();
      if (m[1]) {
        var go = function () { find(m[1]); };
        if (viewer.world.getItemCount()) go(); else viewer.addOnceHandler("open", go);
      }
    }
    applyLayers();
    fromHash();
    window.addEventListener("hashchange", fromHash);

    return {
      hover: hover,
      mm: function (pt) {
        return ((pt.x - data.fid1[0]) / data.pxPerMm).toFixed(1) + ", " + ((pt.y - data.fid1[1]) / data.pxPerMm).toFixed(1) + " mm";
      }
    };
  }
})();
